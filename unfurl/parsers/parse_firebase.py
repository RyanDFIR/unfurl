import re

firebase_edge = {
    'color': {
        'color': '#FFA000'
    },
    'title': 'Firebase Parsing Functions',
    'label': 'FB'
}

# Push IDs are written in this alphabet, which is in ASCII order so the IDs sort
# lexicographically by creation time.
PUSH_CHARS = '-0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ_abcdefghijklmnopqrstuvwxyz'

# 8 timestamp characters followed by 12 random ones. The first timestamp character
# stays '-' until 2109; the second is limited to 'J' through 'P', which covers
# mid-2013 through late 2028. Push IDs were introduced in 2015.
push_id_re = re.compile(r'-[J-P][-0-9A-Za-z_]{18}')

# Plausibility window for the decoded timestamp: 2015-01-01 to 2030-01-01 (UTC).
MIN_TIMESTAMP_MS = 1420070400000
MAX_TIMESTAMP_MS = 1893456000000


def decode_push_id(push_id):
    """Return the millisecond timestamp in the first 8 characters of a push ID."""
    timestamp = 0
    for char in push_id[:8]:
        timestamp = timestamp * 64 + PUSH_CHARS.index(char)
    return timestamp


# Hyphenated page names ('-Onze-nieuwe-schepen', '-P2000-alarmeringen-') can have the
# same length, alphabet and leading characters as a Push ID. Their pieces are words or
# numbers; the pieces of a real Push ID are random mixes of case and digits.
word_piece_re = re.compile(r'[A-Z]?[a-z]+|[A-Z]+|[A-Z]?\d+')
separator_run_re = re.compile(r'[-_]{4,}')


def looks_like_slug(value):
    if separator_run_re.search(value):
        return True
    # Product names like '-MMX-133-MHz-66-MHz-' have pieces that are not plain words,
    # but a real Push ID rarely has 4+ separators and also ends with one.
    if value[-1] in '-_' and len(re.findall(r'[-_]', value[1:])) >= 4:
        return True
    pieces = [piece for piece in re.split(r'[-_]', value[1:]) if piece]
    return len(pieces) >= 2 and all(word_piece_re.fullmatch(piece) for piece in pieces)


def is_push_id(value):
    if not push_id_re.fullmatch(value):
        return False
    if not MIN_TIMESTAMP_MS <= decode_push_id(value) < MAX_TIMESTAMP_MS:
        return False
    return not looks_like_slug(value)


def parse_push_id(unfurl, node):
    # Ref:
    #   - https://firebase.googleblog.com/2015/02/the-2120-ways-to-ensure-unique_68.html
    #   - https://gist.github.com/mikelehen/3596a30bd69384624c11
    timestamp = decode_push_id(node.value)
    random_part = node.value[8:]

    unfurl.add_to_queue(
        data_type='epoch-milliseconds', key=None, value=timestamp, label=f'Timestamp: {timestamp}',
        hover='The first 8 characters of a Firebase Push ID are the time it was created, '
              'in milliseconds',
        parent_id=node.node_id, incoming_edge_config=firebase_edge)

    unfurl.add_to_queue(
        data_type='descriptor', key=None, value=random_part, label=f'Random: {random_part}',
        hover='The last 12 characters of a Firebase Push ID are random. If several IDs are '
              'made in the same millisecond, <br>the random part of each one is the previous '
              'one\'s plus one.',
        parent_id=node.node_id, incoming_edge_config=firebase_edge)


def run(unfurl, node):
    if node.data_type == 'firebase.push_id':
        parse_push_id(unfurl, node)

    elif not node.data_type.startswith(('firebase', 'descriptor')):
        # Google's 'ei' is also 20 URL-safe base64 characters and can start with '-'.
        if node.key == 'ei' and unfurl.preceding_domain_contains(node, 'google'):
            return

        value = str(node.value)
        if is_push_id(value):
            unfurl.add_to_queue(
                data_type='firebase.push_id', key=None, value=value, label=f'Firebase Push ID: {value}',
                hover='Firebase Push IDs are generated by the Firebase Realtime Database for new '
                      'records. <br>They are made of a timestamp and a random part. '
                      '<a href="https://firebase.googleblog.com/2015/02/the-2120-ways-to-ensure-unique_68.html" '
                      'target="_blank">[ref]</a>',
                parent_id=node.node_id, incoming_edge_config=firebase_edge,
                extra_options={'widthConstraint': {'maximum': 300}})
